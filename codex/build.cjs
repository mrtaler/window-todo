const fs = require('node:fs')
const path = require('node:path')
const ts = require('typescript')

// Both adapters use the same reducers. Ship their generated CommonJS so Git installs
// need Node, but do not need npm install or a TypeScript loader at runtime.
const root = path.resolve(__dirname, '..')
const modules = ['activity', 'plan', 'plan-tool', 'sanitize', 'tree', 'window', 'window-tool']
const check = process.argv.includes('--check')
let stale = false
for (const name of modules) {
  const source = fs.readFileSync(path.join(root, 'hooks', `${name}.ts`), 'utf8')
  const compiled = '// Generated by codex/build.cjs from the shared hooks/*.ts sources.\n' + ts.transpileModule(source, {
    compilerOptions: { target: ts.ScriptTarget.ES2023, module: ts.ModuleKind.CommonJS, newLine: ts.NewLineKind.LineFeed },
    fileName: `${name}.ts`,
  }).outputText
  const destination = path.join(__dirname, 'core', `${name}.js`)
  if (check) {
    if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== compiled) {
      console.error(`Stale shared core: codex/core/${name}.js`)
      stale = true
    }
  } else {
    fs.mkdirSync(path.dirname(destination), { recursive: true })
    fs.writeFileSync(destination, compiled)
  }
}
if (stale) process.exitCode = 1
